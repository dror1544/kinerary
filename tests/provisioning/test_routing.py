"""Routing as a choice: a topology with no `npm:` / `cloudflare:` section.

`routing: wildcard` means no proxy host, no DNS record and no tunnel rule for a
trip. These tests prove the three things that must hold at once: a wildcard
topology plans ONE resource and calls NO public-infrastructure adapter, a
topology written before routing existed still loads, plans and means what it
meant, and a section that IS present is never skipped on the strength of a label.
"""
from __future__ import annotations

import unittest
from unittest.mock import Mock, patch

import yaml

from provisioning.__main__ import build_provisioner
from provisioning.engine import Provisioner
from provisioning.models import ProvisioningError, load_topology

# A topology.yaml as control_plane_worker.compute wrote it before routing was a
# choice (the shape of real files: header comment, npm before cloudflare, the
# port only under npm, a vmid written back after apply). Documentation names and
# addresses only.
LEGACY_TOPOLOGY_YAML = """\
# Auto-generated by control_plane_worker.compute.LxcProvisionAdapter for tokyo-2026.
# Written BEFORE apply() runs so a retried job reuses the same IP/hostname
# instead of allocating a second one.
version: 1
name: tokyo-2026
proxmox:
  node: pve
  vmid: '205'
  lxc:
    name: trip-tokyo-2026
    template: local:vztmpl/debian.tar.zst
    storage: local-lvm
    cores: 2
    memory_mb: 1024
    disk_gb: 8
    bridge: vmbr0
    ipv4: 192.0.2.210/24
    gateway: 192.0.2.1
    nameserver: 192.0.2.2
    nfs_host_dir: /mnt/pve/nfs/trip_9f2c11aa4d
    nfs_mount_path: /nfs/trip_9f2c11aa4d
npm:
  hostname: tokyo-2026.example.invalid
  forward_host: 192.0.2.210
  forward_port: 8080
cloudflare:
  tunnel_id: 00000000-0000-0000-0000-000000000000
  hostname: tokyo-2026.example.invalid
  service: http://127.0.0.1:8080
"""

WILDCARD_TOPOLOGY_YAML = """\
version: 1
name: tokyo-2026
routing: wildcard
proxmox:
  node: pve
  vmid: '205'
  lxc:
    name: trip-tokyo-2026
    template: local:vztmpl/debian.tar.zst
    storage: local-lvm
    cores: 2
    memory_mb: 1024
    disk_gb: 8
    bridge: vmbr0
    ipv4: 192.0.2.210/24
    gateway: 192.0.2.1
    nameserver: 192.0.2.2
    nfs_host_dir: /mnt/pve/nfs/trip_9f2c11aa4d
    nfs_mount_path: /nfs/trip_9f2c11aa4d
    forward_port: 8080
    public_hostname: tokyo-2026.example.invalid
"""


def _providers(*, lxc_exists: bool = False):
    proxmox, npm, cloudflare = Mock(), Mock(), Mock()
    proxmox.inspect.return_value = {"vmid": "205", "name": "trip-tokyo-2026"} if lxc_exists else None
    proxmox.needs_bootstrap.return_value = False
    npm.inspect.return_value = None
    cloudflare.inspect.return_value = None
    return proxmox, npm, cloudflare


class LegacyTopologyStillWorks(unittest.TestCase):
    """AC-R2.7: every topology.yaml written before this change parses as `host`,
    plans as it did, and is torn down as it was."""

    def setUp(self) -> None:
        self.topology = load_topology(yaml.safe_load(LEGACY_TOPOLOGY_YAML))

    def test_it_reads_as_host_routing_with_both_public_sections(self) -> None:
        self.assertEqual("host", self.topology.routing)
        self.assertEqual("tokyo-2026.example.invalid", self.topology.proxy.hostname)
        self.assertEqual("192.0.2.210", self.topology.proxy.forward_host)
        self.assertEqual("00000000-0000-0000-0000-000000000000", self.topology.cloudflare.tunnel_id)
        self.assertEqual("http://127.0.0.1:8080", self.topology.cloudflare.service)

    def test_its_origin_and_forward_port_are_what_they_were(self) -> None:
        self.assertEqual("https://tokyo-2026.example.invalid", self.topology.lxc.public_origin)
        self.assertEqual("tokyo-2026.example.invalid", self.topology.public_host)
        # no lxc.forward_port in the file: the site's port is the one under npm
        self.assertEqual(8080, self.topology.lxc.forward_port)

    def test_it_plans_all_three_resources_as_before(self) -> None:
        proxmox, npm, cloudflare = _providers()
        plan = Provisioner(proxmox, npm, cloudflare).plan(self.topology)
        self.assertEqual(
            [("proxmox_lxc", "create"), ("npm_proxy_host", "create"), ("cloudflare_tunnel_dns", "create")],
            [(c.resource, c.operation) for c in plan.changes],
        )

    def test_a_missing_npm_section_is_still_an_error_for_a_host_topology(self) -> None:
        raw = yaml.safe_load(LEGACY_TOPOLOGY_YAML)
        del raw["npm"]
        with self.assertRaisesRegex(ProvisioningError, "npm"):
            load_topology(raw)
        raw = yaml.safe_load(LEGACY_TOPOLOGY_YAML)
        del raw["cloudflare"]
        with self.assertRaisesRegex(ProvisioningError, "cloudflare"):
            load_topology(raw)

    def test_the_example_topology_still_loads(self) -> None:
        env = {
            "ONBOARDING_NAME": "fixture-onboarding", "PROXMOX_NODE": "node", "LXC_NAME": "app",
            "PROXMOX_LXC_TEMPLATE": "template", "PROXMOX_STORAGE": "storage", "PROXMOX_BRIDGE": "bridge",
            "PROXMOX_GATEWAY": "192.0.2.1", "PROXMOX_NAMESERVER": "192.0.2.2",
            "NFS_HOST_DIR": "/mnt/pve/nfs/app", "NFS_MOUNT_PATH": "/nfs/app",
            "PUBLIC_HOSTNAME": "site.example.invalid", "CLOUDFLARE_TUNNEL_ID": "tunnel",
            "CLOUDFLARE_TUNNEL_SERVICE": "http://app:8080",
        }
        with patch.dict("os.environ", env, clear=True):
            from provisioning.__main__ import load_topology_file
            topology = load_topology_file("provisioning/topology.example.yaml")
        self.assertEqual("host", topology.routing)
        self.assertEqual("site.example.invalid", topology.proxy.hostname)


class WildcardTopology(unittest.TestCase):
    def setUp(self) -> None:
        self.topology = load_topology(yaml.safe_load(WILDCARD_TOPOLOGY_YAML))

    def test_it_has_no_public_sections_and_keeps_its_hostname_and_port(self) -> None:
        self.assertEqual("wildcard", self.topology.routing)
        self.assertIsNone(self.topology.proxy)
        self.assertIsNone(self.topology.cloudflare)
        self.assertEqual("tokyo-2026.example.invalid", self.topology.public_host)
        self.assertEqual("https://tokyo-2026.example.invalid", self.topology.lxc.public_origin)
        self.assertEqual(8080, self.topology.lxc.forward_port)

    def test_plan_is_exactly_one_create_for_the_container(self) -> None:
        # AC-R2.2: the three adapters are all there, and only one is asked for.
        proxmox, npm, cloudflare = _providers()
        plan = Provisioner(proxmox, npm, cloudflare).plan(self.topology)
        self.assertEqual([("proxmox_lxc", "create")], [(c.resource, c.operation) for c in plan.changes])
        self.assertEqual(["delete"], [e.operation for e in plan.rollback])

    def test_applying_it_never_touches_npm_or_cloudflare(self) -> None:
        proxmox, npm, cloudflare = _providers()
        Provisioner(proxmox, npm, cloudflare).apply(self.topology, execute=True)
        proxmox.create.assert_called_once_with(self.topology.lxc)
        self.assertEqual([], npm.method_calls)
        self.assertEqual([], cloudflare.method_calls)

    def test_it_needs_no_npm_or_cloudflare_adapter_at_all(self) -> None:
        proxmox, _npm, _cloudflare = _providers()
        plan = Provisioner(proxmox).apply(self.topology, execute=True)
        self.assertEqual(["proxmox_lxc"], [c.resource for c in plan.changes])

    def test_a_present_section_is_planned_whatever_the_routing_label_says(self) -> None:
        # Presence decides. A wildcard-labelled file that still carries an npm:
        # section describes a proxy host that exists; skipping it would leak it.
        raw = yaml.safe_load(WILDCARD_TOPOLOGY_YAML)
        raw["npm"] = {"hostname": "tokyo-2026.example.invalid", "forward_host": "192.0.2.210", "forward_port": 8080}
        topology = load_topology(raw)
        proxmox, npm, cloudflare = _providers()
        plan = Provisioner(proxmox, npm, cloudflare).plan(topology)
        self.assertEqual(["proxmox_lxc", "npm_proxy_host"], [c.resource for c in plan.changes])

    def test_a_section_with_no_adapter_is_refused_not_skipped(self) -> None:
        topology = load_topology(yaml.safe_load(LEGACY_TOPOLOGY_YAML))
        proxmox, _npm, _cloudflare = _providers()
        with self.assertRaisesRegex(ProvisioningError, "no adapter"):
            Provisioner(proxmox).plan(topology)

    def test_a_wildcard_topology_must_say_its_hostname_and_port(self) -> None:
        raw = yaml.safe_load(WILDCARD_TOPOLOGY_YAML)
        del raw["proxmox"]["lxc"]["public_hostname"]
        with self.assertRaisesRegex(ProvisioningError, "public_hostname"):
            load_topology(raw)
        raw = yaml.safe_load(WILDCARD_TOPOLOGY_YAML)
        del raw["proxmox"]["lxc"]["forward_port"]
        with self.assertRaisesRegex(ProvisioningError, "forward_port"):
            load_topology(raw)

    def test_a_hostname_that_disagrees_with_the_proxy_host_is_refused(self) -> None:
        raw = yaml.safe_load(LEGACY_TOPOLOGY_YAML)
        raw["proxmox"]["lxc"]["public_hostname"] = "other.example.invalid"
        with self.assertRaisesRegex(ProvisioningError, "disagrees"):
            load_topology(raw)

    def test_an_unknown_routing_value_is_refused(self) -> None:
        for value in ("path", "Wildcard", "", None, 1):
            with self.subTest(value=value):
                raw = yaml.safe_load(WILDCARD_TOPOLOGY_YAML)
                raw["routing"] = value
                with self.assertRaisesRegex(ProvisioningError, "routing"):
                    load_topology(raw)


class CommandLineProvisioner(unittest.TestCase):
    """`python -m provisioning` asks for NPM and Cloudflare credentials only for
    a topology that has those sections."""

    def test_a_wildcard_topology_needs_neither_npm_nor_cloudflare_credentials(self) -> None:
        topology = load_topology(yaml.safe_load(WILDCARD_TOPOLOGY_YAML))
        with patch.dict("os.environ", {}, clear=True):
            provisioner = build_provisioner(topology)
        self.assertIsNone(provisioner.npm)
        self.assertIsNone(provisioner.cloudflare)

    def test_a_host_topology_still_asks_for_them(self) -> None:
        topology = load_topology(yaml.safe_load(LEGACY_TOPOLOGY_YAML))
        with patch.dict("os.environ", {}, clear=True):
            with self.assertRaisesRegex(ProvisioningError, "NPM_URL"):
                build_provisioner(topology)


if __name__ == "__main__":
    unittest.main()
